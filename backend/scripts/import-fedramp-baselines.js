#!/usr/bin/env node
'use strict';

/**
 * Generates lib/frameworks/fedramp_rev5_baselines.js from FedRAMP's Rev 5
 * security controls baseline workbook, published in the FedRAMP/docs GitHub
 * repository (overrides/assets/LEGACY FedRAMP_Security_Controls_Baseline.xlsx).
 *
 * The workbook lists each baseline's control selection (Low 156, Moderate 323,
 * High 410) with FedRAMP-defined parameter values and additional FedRAMP
 * requirements. FedRAMP marked it legacy on 2026-06-23, superseded by the
 * FedRAMP Consolidated Rules for 2026; it remains the published Rev 5
 * baseline definition.
 *
 *   node scripts/import-fedramp-baselines.js "<path to workbook>.xlsx"
 */

const fs = require('fs');
const path = require('path');
const ExcelJS = require('exceljs');

const SHEETS = { low: 'Low Baseline', moderate: 'Moderate Baseline', high: 'High Baseline' };

function cellText(value) {
  if (value === null || value === undefined) return '';
  if (typeof value === 'object') {
    if (Array.isArray(value.richText)) return value.richText.map((r) => r.text).join('');
    if ('result' in value) return cellText(value.result);
    if ('text' in value) return String(value.text);
  }
  return String(value);
}

function clean(text) {
  return text.replace(/\r\n?/g, '\n').split('\n').map((l) => l.trimEnd()).join('\n').trim();
}

// "AC-2 (1)" -> "AC-2(1)", matching scripts/lib/frameworks/nist_800_53.js.
function normalizeId(raw) {
  return raw.trim().replace(/\s*\(\s*/g, '(').replace(/\s*\)/g, ')').toUpperCase();
}

async function main() {
  const source = process.argv[2];
  if (!source) {
    process.stderr.write('usage: node scripts/import-fedramp-baselines.js <FedRAMP_Security_Controls_Baseline.xlsx>\n');
    process.exit(1);
  }
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(path.resolve(source));

  const baselines = {};
  for (const [key, sheetName] of Object.entries(SHEETS)) {
    const ws = wb.getWorksheet(sheetName);
    if (!ws) throw new Error(`Sheet "${sheetName}" not found`);
    const rows = [];
    ws.eachRow((row, n) => {
      if (n < 3) return;
      const id = cellText(row.getCell(3).value);
      if (!/^[A-Z]{2}-\d/.test(id.trim())) return;
      rows.push({
        control_id: normalizeId(id),
        fedramp_parameters: clean(cellText(row.getCell(7).value)),
        fedramp_requirements: clean(cellText(row.getCell(8).value))
      });
    });
    baselines[key] = rows;
  }

  const out = path.join(__dirname, 'lib', 'frameworks', 'fedramp_rev5_baselines.js');
  const header = [
    '// Auto-generated by scripts/import-fedramp-baselines.js from FedRAMP\'s Rev 5',
    '// security controls baseline workbook (FedRAMP/docs, "LEGACY',
    '// FedRAMP_Security_Controls_Baseline.xlsx"). FedRAMP marked the workbook',
    '// legacy on 2026-06-23 in favor of the FedRAMP Consolidated Rules for 2026.',
    '// Do not hand-edit -- re-run the importer.',
    '// ip-hygiene:ignore-file (FedRAMP and NIST publications are US government works)',
    ''
  ].join('\n');
  fs.writeFileSync(out, `${header}'use strict';\n\nmodule.exports = ${JSON.stringify(baselines, null, 2)};\n`);
  process.stdout.write(`Wrote ${path.relative(process.cwd(), out)}: ${Object.entries(baselines).map(([k, v]) => `${k} ${v.length}`).join(', ')}\n`);
}

main().catch((err) => { process.stderr.write(`${err.message}\n`); process.exit(1); });
