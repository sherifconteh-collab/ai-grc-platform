#!/usr/bin/env node
'use strict';

/**
 * Imports a DISA STIG XCCDF benchmark as a framework data module in
 * lib/frameworks/supplemental/<code>.js, crosswalked to NIST SP 800-53 Rev 5
 * through each rule's CCIs (lib/frameworks/cci_nist_rev5.js). Seed it with
 * scripts/seed-stig-benchmark.js.
 *
 * Download benchmarks from public.cyber.mil/stigs/downloads (the
 * U_<name>_STIG_V<v>R<r>_Manual-xccdf.xml file inside the zip).
 *
 *   node scripts/import-stig-xccdf.js <benchmark-xccdf.xml> --code disa_stig_rhel8 [--tier community]
 */

const fs = require('fs');
const path = require('path');
const { parseBenchmark } = require('./lib/stig/xccdf');
const CCI = require('./lib/frameworks/cci_nist_rev5');

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
}

// DISA publishes "Version 6" plus "Release: 4"; the catalog and the quarterly
// version check (check-stig-versions.js) use the V6R4 form.
function stigVersion(bench) {
  const release = /Release:\s*(\d+)\s*(?:Benchmark|$)/.exec(bench.release_info || '');
  if (/^\d+$/.test(bench.version) && release) return `V${Number(bench.version)}R${release[1]}`;
  return bench.release_info ? bench.release_info.replace(/\s+/g, ' ') : bench.version;
}

async function main() {
  const source = process.argv[2];
  const code = arg('--code');
  if (!source || !code || !/^[a-z0-9_]+$/.test(code)) {
    process.stderr.write('usage: node scripts/import-stig-xccdf.js <benchmark-xccdf.xml> --code <lowercase_code> [--tier community]\n');
    process.exit(1);
  }
  const bench = await parseBenchmark(fs.readFileSync(path.resolve(source), 'utf8'), CCI.rev5);
  const framework = {
    code,
    name: bench.title,
    version: stigVersion(bench),
    category: 'Cybersecurity',
    tier_required: arg('--tier', 'community'),
    description: bench.description,
    source: {
      benchmark: path.basename(source),
      status_date: bench.status_date,
      cci_list: CCI.version
    },
    controls: bench.controls
  };
  const out = path.join(__dirname, 'lib', 'frameworks', 'supplemental', `${code}.js`);
  const header = [
    `// Auto-generated by scripts/import-stig-xccdf.js from ${path.basename(source)}.`,
    '// Do not hand-edit -- re-run the importer against a newer benchmark.',
    '// ip-hygiene:ignore-file (DISA STIGs are US government works)',
    ''
  ].join('\n');
  fs.writeFileSync(out, `${header}'use strict';\n\nmodule.exports = ${JSON.stringify(framework, null, 2)};\n`);
  const mapped = bench.controls.filter((c) => c.nist_800_53.length).length;
  process.stdout.write(`Wrote ${bench.controls.length} rules to ${path.relative(process.cwd(), out)}; ${mapped} crosswalk to 800-53 Rev 5.\n`);
  if (bench.duplicate_rules_dropped.length) {
    const list = bench.duplicate_rules_dropped.map((d) => `${d.control_id} (${d.vuln_id})`).join(', ');
    process.stdout.write(`Kept the newest rule where an id repeats; dropped: ${list}\n`);
  }
  if (bench.unmapped_ccis.length) {
    process.stdout.write(`CCIs with no 800-53 Rev 5 reference in DISA's list ${CCI.version}: ${bench.unmapped_ccis.join(', ')}\n`);
  }
}

main().catch((err) => { process.stderr.write(`${err.message}\n`); process.exit(1); });
