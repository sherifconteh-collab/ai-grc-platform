#!/usr/bin/env node
'use strict';

/**
 * Generates lib/frameworks/nist_800_171_rev3.js from NIST's SP 800-171 Rev 3
 * OSCAL catalog, the same source and rendering as migration 156, so a fresh
 * seed installs the same 97 requirements an upgraded database has.
 *
 *   curl -sLo catalog.json https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-171/rev3/json/NIST_SP800-171_rev3_catalog.json
 *   node scripts/import-oscal-800171.js catalog.json
 */

const fs = require('fs');
const path = require('path');
const { buildRows, priorityFor } = require('./lib/oscal/sp800171');

const source = process.argv[2];
if (!source) {
  process.stderr.write('usage: node scripts/import-oscal-800171.js <NIST_SP800-171_rev3_catalog.json>\n');
  process.exit(1);
}

const catalog = JSON.parse(fs.readFileSync(path.resolve(source), 'utf8')).catalog;
const controls = buildRows(catalog).map((r) => ({
  control_id: r.id,
  title: r.title,
  description: r.desc,
  priority: priorityFor(r.id),
  control_type: r.type,
  family: r.family
}));

const out = path.join(__dirname, 'lib', 'frameworks', 'nist_800_171_rev3.js');
const header = [
  '// Auto-generated by scripts/import-oscal-800171.js from NIST\'s OSCAL',
  '// catalog (usnistgov/oscal-content nist.gov/SP800-171/rev3). Withdrawn',
  '// Rev 3 identifiers are omitted. Do not hand-edit -- re-run the importer.',
  `// Catalog version: ${catalog.metadata.version}; last modified ${catalog.metadata['last-modified']}.`,
  ''
].join('\n');
fs.writeFileSync(out, `${header}'use strict';\n\nmodule.exports = ${JSON.stringify({ version: catalog.metadata.version, controls }, null, 2)};\n`);
process.stdout.write(`Wrote ${controls.length} requirements to ${path.relative(process.cwd(), out)}\n`);
