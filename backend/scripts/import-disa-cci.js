#!/usr/bin/env node
'use strict';

/**
 * Generates lib/frameworks/cci_nist_rev5.js, DISA's mapping from Control
 * Correlation Identifiers to NIST SP 800-53 Rev 5 controls, from DISA's CCI
 * list (U_CCI_List.xml, published at public.cyber.mil/stigs/cci and mirrored
 * in mitre/heimdall2 libs/hdf-converters/src/utils/CCI_List.ts). STIG rules
 * cite CCIs, so this is what crosswalks an imported STIG to 800-53.
 *
 *   node scripts/import-disa-cci.js U_CCI_List.xml
 */

const fs = require('fs');
const path = require('path');
const { parseCciList } = require('./lib/stig/cci');

async function main() {
  const source = process.argv[2];
  if (!source) {
    process.stderr.write('usage: node scripts/import-disa-cci.js <U_CCI_List.xml>\n');
    process.exit(1);
  }
  const { version, publishdate, rev5 } = await parseCciList(fs.readFileSync(path.resolve(source), 'utf8'));
  const out = path.join(__dirname, 'lib', 'frameworks', 'cci_nist_rev5.js');
  const header = [
    '// Auto-generated by scripts/import-disa-cci.js from DISA\'s CCI list.',
    '// Maps each CCI to the NIST SP 800-53 Rev 5 control ids it references.',
    '// Do not hand-edit -- re-run the importer.',
    '// ip-hygiene:ignore-file (DISA and NIST publications are US government works)',
    ''
  ].join('\n');
  const body = Object.keys(rev5).sort().map((id) => `    ${JSON.stringify(id)}: ${JSON.stringify(rev5[id])}`).join(',\n');
  fs.writeFileSync(out, `${header}'use strict';\n\nmodule.exports = {\n  version: ${JSON.stringify(version)},\n  publishdate: ${JSON.stringify(publishdate)},\n  rev5: {\n${body}\n  }\n};\n`);
  process.stdout.write(`Wrote ${Object.keys(rev5).length} CCIs (list ${version}) to ${path.relative(process.cwd(), out)}\n`);
}

main().catch((err) => { process.stderr.write(`${err.message}\n`); process.exit(1); });
