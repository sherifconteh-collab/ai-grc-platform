#!/usr/bin/env node
'use strict';

/**
 * Writes migrations/161_fedramp_rev5_baselines.sql from
 * backend/scripts/lib/frameworks/fedramp_baselines.js, so existing databases
 * receive the FedRAMP Rev 5 baselines seed-frameworks.js installs on fresh
 * ones (issue #217). The migration also loads all 97
 * SP 800-171 Rev 3 requirements (this repo seeded and shipped only 24).
 *
 *   node scripts/generate-fedramp-migration.js          write the file
 *   node scripts/generate-fedramp-migration.js --check  fail if stale
 *
 * The migration is deployed once it ships; later content changes belong in a
 * new migration rather than a regenerated 170.
 */

const fs = require('fs');
const path = require('path');
const { frameworks: fedramp } = require('./lib/frameworks/fedramp_baselines');
const nist800171 = require('./lib/frameworks/nist_800_171');

const frameworks = [nist800171, ...fedramp];

const TARGET = path.join(__dirname, '..', 'migrations', '161_fedramp_rev5_baselines.sql');

function lit(value) {
  if (value === null || value === undefined) return 'NULL';
  const text = String(value);
  if (text.includes('$cw$')) throw new Error(`Content may not contain $cw$: ${text.slice(0, 40)}`);
  return `$cw$${text}$cw$`;
}

function frameworkBlock(fw) {
  const rows = fw.controls
    .map((c) => `      (${[c.control_id, c.title, c.description, c.control_type, c.priority].map(lit).join(', ')}, ${c.is_enhancement ? 'true' : 'false'})`)
    .join(',\n');
  const children = fw.controls.filter((c) => c.parent_control_id);
  return `  -- ${fw.code}: ${fw.controls.length} controls
  SELECT id INTO fw_id FROM frameworks WHERE code = ${lit(fw.code)} ORDER BY created_at LIMIT 1;
  IF fw_id IS NULL THEN
    INSERT INTO frameworks (code, name, version, description, category, tier_required, is_active, coverage_status)
    VALUES (${[fw.code, fw.name, fw.version, fw.description, fw.category, fw.tier_required].map(lit).join(', ')}, true, 'comprehensive')
    RETURNING id INTO fw_id;
  ELSE
    UPDATE frameworks
       SET name = ${lit(fw.name)}, version = ${lit(fw.version)}, description = ${lit(fw.description)},
           category = ${lit(fw.category)}, coverage_status = 'comprehensive'
     WHERE id = fw_id;
  END IF;

  INSERT INTO framework_controls (framework_id, control_id, title, description, control_type, priority, is_enhancement)
  SELECT fw_id, v.control_id, v.title, v.description, v.control_type, v.priority, v.is_enhancement
    FROM (VALUES
${rows}
    ) AS v(control_id, title, description, control_type, priority, is_enhancement)
  ON CONFLICT (framework_id, control_id) DO UPDATE
    SET title = EXCLUDED.title, description = EXCLUDED.description, control_type = EXCLUDED.control_type,
        priority = EXCLUDED.priority, is_enhancement = EXCLUDED.is_enhancement;

${children.length ? `  UPDATE framework_controls child
     SET parent_control_id = parent.id
    FROM (VALUES
${children.map((c) => `      (${lit(c.control_id)}, ${lit(c.parent_control_id)})`).join(',\n')}
    ) AS v(control_id, parent_code)
    JOIN framework_controls parent ON parent.framework_id = fw_id AND parent.control_id = v.parent_code
   WHERE child.framework_id = fw_id AND child.control_id = v.control_id
     AND child.parent_control_id IS DISTINCT FROM parent.id;` : ''}
`;
}

function render() {
  const counts = fedramp.map((fw) => `${fw.code} ${fw.controls.length}`).join(', ');
  return `-- Migration 161: FedRAMP Rev 5 baselines
--
-- Generated by scripts/generate-fedramp-migration.js from
-- backend/scripts/lib/frameworks/fedramp_baselines.js. Do not edit by hand.
--
-- Why (issue #217): this repository carried only a 25-control hand-written
-- FedRAMP High stub, created by the destructive seed and never by a migration,
-- and no Low or Moderate baseline. FedRAMP's own Rev 5 baselines select
-- ${counts}.
-- The selection and FedRAMP's defined parameter values and additional
-- requirements come from FedRAMP's Rev 5 baseline workbook (FedRAMP/docs),
-- which FedRAMP marked legacy on 2026-06-23 in favor of the FedRAMP
-- Consolidated Rules for 2026. Control text is NIST SP 800-53 Rev 5's.
--
-- Idempotent: frameworks are matched on code, controls on (framework_id,
-- control_id). Existing rows keep their ids (and are normalized to the numeric
-- 1/2/3 priority scale the stub's 'high' text did not use), so implementations,
-- evidence links and crosswalks are untouched, and no control is removed. Seven rows of
-- the old hand-written High stub (FRH-CP-7(5), FRH-PL-8(1), FRH-PS-6(3),
-- FRH-SA-10(1), FRH-SC-5(3), FRH-SC-19, FRH-SI-7(14)) are not in FedRAMP's
-- Rev 5 High selection (two are withdrawn in Rev 5). They are left in place on
-- deployed databases, because deleting them would cascade to any assessments
-- recorded against them; fresh installs never create them.
--
-- Ships in the release that follows 2026.9.0 (see RELEASE_NOTES.md).

DO $$
DECLARE
  fw_id UUID;
BEGIN
${frameworks.map(frameworkBlock).join('\n')}
END $$;

SELECT 'Migration 161 completed.' AS result;
`;
}

function main() {
  const output = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (current !== output) {
      process.stderr.write(`${path.basename(TARGET)} is out of date. Run: node scripts/generate-fedramp-migration.js\n`);
      process.exit(1);
    }
    process.stdout.write(`${path.basename(TARGET)} is up to date.\n`);
    return;
  }
  fs.writeFileSync(TARGET, output);
  process.stdout.write(`Wrote ${path.relative(process.cwd(), TARGET)} (${output.length} bytes)\n`);
}

if (require.main === module) main();

module.exports = { render };
