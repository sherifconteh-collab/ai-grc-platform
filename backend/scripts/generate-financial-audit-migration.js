#!/usr/bin/env node
'use strict';

/**
 * Writes migrations/162_financial_audit_content.sql from
 * scripts/lib/frameworks/financialAudit.js, so existing databases receive the
 * same content that seed-frameworks.js installs on fresh ones.
 *
 *   node scripts/generate-financial-audit-migration.js          write the file
 *   node scripts/generate-financial-audit-migration.js --check  fail if stale
 *
 * The migration is already deployed once it ships; after that, content changes
 * belong in a new migration rather than a regenerated 162.
 */

const fs = require('fs');
const path = require('path');
const content = require('./lib/frameworks/financialAudit');

const TARGET = path.join(__dirname, '..', 'migrations', '162_financial_audit_content.sql');

function lit(value) {
  if (value === null || value === undefined) return 'NULL';
  const text = String(value);
  if (text.includes('$cw$')) throw new Error(`Content may not contain $cw$: ${text.slice(0, 40)}`);
  return `$cw$${text}$cw$`;
}

function controlValues(controls) {
  return controls
    .map((ctl) => `      (${[ctl.control_id, ctl.title, ctl.description, ctl.control_type, ctl.priority, ctl.parent_control_id || null].map(lit).join(', ')})`)
    .join(',\n');
}

function upsertControls(fwVar, controls) {
  const children = controls.filter((ctl) => ctl.parent_control_id);
  return `  INSERT INTO framework_controls (framework_id, control_id, title, description, control_type, priority)
  SELECT ${fwVar}, v.control_id, v.title, v.description, v.control_type, v.priority
    FROM (VALUES
${controlValues(controls)}
    ) AS v(control_id, title, description, control_type, priority, parent_code)
  ON CONFLICT (framework_id, control_id) DO UPDATE
    SET title = EXCLUDED.title, description = EXCLUDED.description, control_type = EXCLUDED.control_type;${children.length ? `

  UPDATE framework_controls child
     SET parent_control_id = parent.id
    FROM (VALUES
${children.map((ctl) => `      (${lit(ctl.control_id)}, ${lit(ctl.parent_control_id)})`).join(',\n')}
    ) AS v(control_id, parent_code)
    JOIN framework_controls parent ON parent.framework_id = ${fwVar} AND parent.control_id = v.parent_code
   WHERE child.framework_id = ${fwVar} AND child.control_id = v.control_id
     AND child.parent_control_id IS DISTINCT FROM parent.id;` : ''}`;
}

function frameworkBlock(fw) {
  return `  SELECT id INTO fw_id FROM frameworks WHERE code = ${lit(fw.code)} ORDER BY created_at LIMIT 1;
  IF fw_id IS NULL THEN
    INSERT INTO frameworks (code, name, version, description, category, tier_required, is_active, coverage_status)
    VALUES (${[fw.code, fw.name, fw.version, fw.description, fw.category, fw.tier_required].map(lit).join(', ')}, true, ${lit(fw.coverage_status)})
    RETURNING id INTO fw_id;
  ELSE
    UPDATE frameworks
       SET name = ${lit(fw.name)}, version = ${lit(fw.version)}, description = ${lit(fw.description)},
           category = ${lit(fw.category)}, coverage_status = ${lit(fw.coverage_status)}
     WHERE id = fw_id;
  END IF;

${upsertControls('fw_id', fw.controls)}
`;
}

function render() {
  const total = content.FISCAM_ADDITIONS.length + content.NEW_FRAMEWORKS.reduce((n, fw) => n + fw.controls.length, 0);
  return `-- Migration 162: Financial audit readiness content
--
-- Generated by scripts/generate-financial-audit-migration.js from
-- scripts/lib/frameworks/financialAudit.js. Do not edit by hand.
--
-- Why: ERP and federal financial-management customers are audited against
-- FISCAM, SOX 404 and OMB A-123, and the platform had only twelve summary
-- FISCAM controls and no COSO, SOX ITGC or A-123 content. This adds
-- ${total} ControlWeave-authored controls:
--   * FISCAM: business process, interface and data management families, and
--     control activities (CWF- prefix) under every family
--   * COSO 2013: five components and seventeen principles (paraphrased)
--   * SOX IT general controls library
--   * OMB A-123 Appendix A readiness checklist
-- Identifiers are ControlWeave's own, not official numbering.
--
-- Idempotent: frameworks are matched on code, controls on (framework_id,
-- control_id); existing rows keep their ids so implementations and evidence
-- links are untouched. FISCAM additions are skipped when the fiscam framework
-- is not installed yet (seed-frameworks.js installs them with it).

DO $$
DECLARE
  fw_id UUID;
BEGIN
  SELECT id INTO fw_id FROM frameworks WHERE code = 'fiscam' ORDER BY created_at LIMIT 1;
  IF fw_id IS NULL THEN
    RAISE NOTICE 'fiscam framework not present; skipping FISCAM additions';
  ELSE
${upsertControls('fw_id', content.FISCAM_ADDITIONS).replace(/^/gm, '  ')}
  END IF;

${content.NEW_FRAMEWORKS.map(frameworkBlock).join('\n')}END $$;

SELECT 'Migration 162 completed.' AS result;
`;
}

function main() {
  const output = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (current !== output) {
      process.stderr.write(`${path.basename(TARGET)} is out of date. Run: node scripts/generate-financial-audit-migration.js\n`);
      process.exit(1);
    }
    process.stdout.write(`${path.basename(TARGET)} is up to date.\n`);
    return;
  }
  fs.writeFileSync(TARGET, output);
  process.stdout.write(`Wrote ${path.relative(process.cwd(), TARGET)}\n`);
}

if (require.main === module) main();

module.exports = { render };
